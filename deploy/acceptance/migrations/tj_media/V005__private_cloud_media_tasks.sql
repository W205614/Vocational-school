CREATE TABLE cloud_media_upload (
 id CHAR(36) PRIMARY KEY,
 owner_id BIGINT NOT NULL,
 idempotency_key VARCHAR(128) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 filename VARCHAR(255) NOT NULL,
 expected_size BIGINT NOT NULL,
 expected_sha256 CHAR(64) NOT NULL,
 source_key VARCHAR(200) NOT NULL,
 state VARCHAR(16) NOT NULL DEFAULT 'UPLOADING',
 expires_at DATETIME(3) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 lease_token CHAR(36),
 lease_until DATETIME(3),
 attempts INT NOT NULL DEFAULT 0,
 object_key VARCHAR(200),
 object_version VARCHAR(200),
 object_etag VARCHAR(200),
 output_size BIGINT,
 output_sha256 CHAR(64),
 duration_seconds FLOAT,
 media_id BIGINT,
 error_code VARCHAR(64),
 UNIQUE KEY uq_cloud_upload_request(owner_id,idempotency_key),
 KEY ix_cloud_upload_work(state,next_attempt_at,lease_until)
) ENGINE=InnoDB;
